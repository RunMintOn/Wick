const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {exec}=require('./helpers.cjs');
const script=path.resolve(__dirname,'../scripts/install-skill.cjs');
test('install the Chinese Skill once and preserve an unrelated existing Skill',async()=>{
  const home=await fs.mkdtemp(path.join(os.tmpdir(),'localdeck-skill-test-'));
  const options={env:{...process.env,HOME:home}};
  const target=path.join(home,'.agents','skills','localdeck');
  await exec(process.execPath,[script],options);
  assert.equal(await fs.realpath(target),path.resolve(__dirname,'../skills/localdeck'));
  await exec(process.execPath,[script],options);
  await fs.access(path.join(target,'references','takeover.md'));
  const otherHome=await fs.mkdtemp(path.join(os.tmpdir(),'localdeck-skill-test-'));
  const otherTarget=path.join(otherHome,'.agents','skills','localdeck');await fs.mkdir(otherTarget,{recursive:true});
  await fs.writeFile(path.join(otherTarget,'SKILL.md'),'User-owned Skill');
  await assert.rejects(exec(process.execPath,[script],{env:{...process.env,HOME:otherHome}}),/Existing Skill is preserved/);
  assert.equal(await fs.readFile(path.join(otherTarget,'SKILL.md'),'utf8'),'User-owned Skill');
});
