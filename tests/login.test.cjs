const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const YAML=require('yaml');
const {installLogin}=require('../src/login.cjs');
const {fixture,web,reachable,cleanup,exec,waitFor}=require('./helpers.cjs');
test('real isolated launchd job boots and supervises the background without Electron UI',async t=>{
 const {home,manager}=await fixture();
 const label=`dev.wick.test.${process.pid}`;
 const domain=`gui/${process.getuid()}`;
 t.after(async()=>{await exec('/bin/launchctl',['bootout',`${domain}/${label}`]).catch(()=>{});await cleanup(manager);});
 await fs.writeFile(manager.config,YAML.stringify({version:'0.5',processes:{web:{...web(home),disabled:false},manual:web(home,'manual')}}));
 await installLogin(manager,{label,agentPath:path.join(home,'agent.plist'),executable:process.execPath});
 await reachable(home);
 const snapshot=await manager.snapshot();assert.equal(snapshot.services.find(s=>s.name==='manual').is_running,false);
 const output=await exec('/bin/launchctl',['print',`${domain}/${label}`]);assert.match(output.stdout,/state = running/);
 const service=snapshot.services.find(s=>s.name==='web');
 const parent=Number((await exec('/bin/ps',['-o','ppid=','-p',String(service.pid)])).stdout.trim());
 assert.equal(Number((await exec('/bin/ps',['-o','ppid=','-p',String(parent)])).stdout.trim()),1);
 await manager.action('stop','web');await waitFor(async()=>!(await manager.snapshot()).services.find(s=>s.name==='web').is_running);
 await installLogin(manager,{label,agentPath:path.join(home,'agent.plist'),executable:process.execPath});
 assert.equal((await manager.snapshot()).services.find(s=>s.name==='web').is_running,false);
});
