const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const YAML=require('yaml');
const {fixture,web,reachable,waitFor,cleanup,exec}=require('./helpers.cjs');
test('CLI and console connection manage one detached service',async t=>{
  const {home,manager}=await fixture();t.after(()=>cleanup(manager));
  await fs.writeFile(path.join(home,'services.yaml'),YAML.stringify({version:'0.5',processes:{web:web(home)}}));
  await manager.ensure();
  assert.equal((await manager.snapshot()).services[0].is_running,false);
  await manager.action('start','web');await reachable(home);
  const first=(await manager.snapshot()).services[0].pid;
  await manager.ensure();assert.equal((await manager.snapshot()).services[0].pid,first);
  await manager.action('restart','web');await reachable(home);
  assert.notEqual((await manager.snapshot()).services[0].pid,first);
  await exec(manager.binary,['-U','-u',manager.socket,'process','stop','web']);
  await waitFor(async()=>!(await manager.snapshot()).services[0].is_running);
  await assert.rejects(fetch(`http://127.0.0.1:${await fs.readFile(path.join(home,'web.port'),'utf8')}`));
});
